create table if not exists public.road_closure_requests (
 id bigint generated by default as identity primary key,
 reference text unique not null,
 location text not null,
 closure_type text not null,
 reason text not null,
 priority text not null default 'ROUTINE',
 agency text,
 requesting_officer text not null,
 notes text,
 status text not null default 'PENDING',
 created_at timestamptz not null default now()
);
alter table public.road_closure_requests enable row level security;
grant insert on public.road_closure_requests to anon;
grant select, update on public.road_closure_requests to authenticated;
grant usage, select on sequence public.road_closure_requests_id_seq to anon, authenticated;
drop policy if exists "LEO submit road closure" on public.road_closure_requests;
create policy "LEO submit road closure" on public.road_closure_requests for insert to anon with check (status='PENDING');
drop policy if exists "DOT view road closures" on public.road_closure_requests;
create policy "DOT view road closures" on public.road_closure_requests for select to authenticated using (public.is_dot_staff());
drop policy if exists "DOT update road closures" on public.road_closure_requests;
create policy "DOT update road closures" on public.road_closure_requests for update to authenticated using (public.is_dot_staff()) with check (public.is_dot_staff());
notify pgrst, 'reload schema';
