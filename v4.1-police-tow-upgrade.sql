-- DOT Impound v4.1 - Police Tow Request upgrade
-- Safe additive upgrade for the v4 Shared baseline.
create table if not exists public.tow_requests (
  id bigint generated by default as identity primary key,
  reference text unique generated always as ('TR-' || lpad(id::text, 4, '0')) stored,
  registration text not null,
  vehicle text not null,
  colour text,
  reason text not null,
  priority text not null default 'ROUTINE' check (priority in ('ROUTINE','URGENT','EMERGENCY')),
  location text not null,
  agency text not null,
  requesting_officer text not null,
  destination text,
  notes text,
  status text not null default 'PENDING' check (status in ('PENDING','CLAIMED','EN ROUTE','ON SCENE','COMPLETE','IMPOUNDED','CANCELLED')),
  claimed_by text,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);
create index if not exists tow_requests_status_idx on public.tow_requests(status);
create index if not exists tow_requests_registration_idx on public.tow_requests(upper(registration));
alter table public.tow_requests enable row level security;
grant insert on public.tow_requests to anon;
grant usage, select on sequence public.tow_requests_id_seq to anon;
grant select, update on public.tow_requests to authenticated;
drop policy if exists "Police can submit tow requests" on public.tow_requests;
create policy "Police can submit tow requests" on public.tow_requests for insert to anon with check (status='PENDING' and claimed_by is null and completed_at is null);
drop policy if exists "DOT staff can view tow requests" on public.tow_requests;
create policy "DOT staff can view tow requests" on public.tow_requests for select to authenticated using (public.is_dot_staff());
drop policy if exists "DOT staff can update tow requests" on public.tow_requests;
create policy "DOT staff can update tow requests" on public.tow_requests for update to authenticated using (public.is_dot_staff()) with check (public.is_dot_staff());
