create table if not exists public.vehicle_checklists (
  id bigint generated by default as identity primary key,
  operator_id uuid not null references auth.users(id) on delete cascade,
  operator_username text not null,
  unit_number text not null,
  vehicle text not null,
  checks jsonb not null default '{}'::jsonb,
  completed_at timestamptz not null default now()
);

alter table public.vehicle_checklists enable row level security;

drop policy if exists "DOT staff can read own checklists" on public.vehicle_checklists;
create policy "DOT staff can read own checklists"
on public.vehicle_checklists for select
to authenticated
using (operator_id = auth.uid());

drop policy if exists "DOT staff can file own checklists" on public.vehicle_checklists;
create policy "DOT staff can file own checklists"
on public.vehicle_checklists for insert
to authenticated
with check (operator_id = auth.uid());

grant select, insert on public.vehicle_checklists to authenticated;
grant usage, select on sequence public.vehicle_checklists_id_seq to authenticated;
notify pgrst, 'reload schema';
